const LanguageContext = createContext(null);
const STORAGE_KEY = "infy_language";
const supportedCodes = new Set(LANGUAGES.map(({ code }) => code));

function getInitialLanguage() {
  if (typeof window === "undefined") return "en";
  try {
    const storedLanguage = window.localStorage.getItem(STORAGE_KEY);
    return supportedCodes.has(storedLanguage) ? storedLanguage : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  const setLanguage = (nextLanguage) => {
    setLanguageState(supportedCodes.has(nextLanguage) ? nextLanguage : "en");
  };

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Storage may be unavailable in private or restricted browsing contexts.
    }
  }, [language]);

  const locale = LANGUAGES.find(({ code }) => code === language)?.locale ?? "en";
  const t = useCallback((englishText) => additionalTranslations[language]?.[englishText]
    ?? translations[language]?.[englishText]
    ?? englishText, [language]);
  const value = useMemo(() => ({ language, setLanguage, t, locale }), [language, locale, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// Exporting this hook alongside its provider keeps the context API in one module.
// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}

export function LanguageSelector({ className = "", ...props }) {
  const { language, setLanguage, t } = useLanguage();

  return (
    <label className={`language-selector ${className}`.trim()}>
      <Languages aria-hidden="true" size={18} />
      <span className="sr-only">{t("Language")}</span>
      <select
        aria-label={t("Language")}
        value={language}
        onChange={(event) => setLanguage(event.target.value)}
        {...props}
      >
        {LANGUAGES.map(({ code, name }) => (
          <option key={code} value={code}>
            {name}
          </option>
        ))}
      </select>
    </label>
  );
}
